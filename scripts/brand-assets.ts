// The transparent lockup is the only artwork source; derive repository and tab variants from it.
import { readFileSync, writeFileSync } from "node:fs"

const directory = new URL("../assets/brand/", import.meta.url)
const logo = readFileSync(new URL("logo.svg", directory), "utf8")
const body = logo.replace(/^[\s\S]*?<svg\b[^>]*>/, "").replace(/<\/svg>\s*$/, "")
const mark = body.match(/<g id="arena-mark"[\s\S]*?<\/g>/)?.[0]
if (!mark) throw new Error("logo.svg is missing arena-mark")
const generated = "<!-- Generated by scripts/brand-assets.ts from logo.svg; edit the source logo. -->"
writeFileSync(new URL("favicon.svg", directory), `<svg xmlns="http://www.w3.org/2000/svg" width="64" height="64" viewBox="0 0 64 64">${generated}<title>RTS Arena</title><rect width="64" height="64" rx="13" fill="#142128"/><g transform="translate(6 1)">${mark}</g></svg>\n`)
writeFileSync(new URL("repository.svg", directory), `<svg xmlns="http://www.w3.org/2000/svg" width="600" height="176" viewBox="0 0 600 176">${generated}<rect width="600" height="176" rx="18" fill="#142128"/><g transform="translate(51.6 30.4) scale(1.8)">${body}</g></svg>\n`)
